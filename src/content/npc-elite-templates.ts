const attack = (
  id: string,
  name: string,
  bonus: number,
  damage: string,
  damageType: NpcAttack['damageType'],
  range = 0,
  longRange = range,
  extraDamage?: NpcAttack['extraDamage'],
): NpcAttack => ({
  id,
  name,
  bonus,
  damage,
  damageType,
  reach: 5,
  range,
  longRange,
  ...(['shortbow','longbow','crossbow','javelin-thrown','dagger-thrown'].includes(id)?{projectile:'ordinary' as const}:['rock','boulder'].includes(id)?{projectile:'massive' as const}:{}),
  kind: id.endsWith('-thrown') ? 'thrown' : 'weapon',
  ...(extraDamage ? { extraDamage } : {}),
})
const pool = (id: string, name: string, max: number): Pool => ({
  id,
  name,
  max,
  remaining: max,
  recovery: 'day',
})
const spell = (
  id: string,
  name: string,
  cost: Power['cost'],
  resourceId?: string,
  slotLevel = 1,
  support: Power['support'] = 'automatic',
): Power => ({
  id,
  name,
  cost,
  resourceId,
  spellId: id,
  slotLevel,
  support,
  note: support === 'gm' ? '完整效果／空间／目标由GM按原书裁定；此入口登记原书预算及资源' : '',
})
const gm = (id: string, name: string, cost: Power['cost'] = 'action'): Power => ({
  id,
  name,
  cost,
  support: 'gm',
  note: 'GM确认条件并使用原裁定入口处理效果',
})
function make(
  id: string,
  name: string,
  englishName: string,
  page: number,
  cr: string,
  xp: number,
  hitDice: string,
  ac: number,
  hp: number,
  speed: number,
  scores: number[],
  attacks: NpcAttack[],
  extra: Partial<CombatNpc> = {},
  meta: Partial<Meta> = {},
): NpcTemplate {
  const keys: Ability[] = ['str', 'dex', 'con', 'int', 'wis', 'cha'],
    values = Object.fromEntries(keys.map((k, i) => [k, scores[i]!])) as Record<Ability, number>
  const saves = Object.fromEntries(
    keys.map((k) => [k, Math.floor((values[k] - 10) / 2)]),
  ) as Record<Ability, number>
  const source = `SRD 5.2.1，第${page}页；https://www.dndbeyond.com/srd`
  const metadata: Meta = {
    englishName,
    category: 'civilian',
    sourceVersion: 'SRD 5.2.1',
    templateVersion: '1.0.0',
    pages: [page],
    cr,
    xp,
    proficiencyBonus: cr === '6' ? 3 : 2,
    alignment: '中立',
    hitDice,
    skills: {},
    senses: [],
    passivePerception: 10,
    languages: ['通用语'],
    movement: [],
    gear: [],
    tags: extra.spellcasting ? ['caster'] : ['elite'],
    requiresManualTurn: !!extra.abilities?.some((a) => a.support !== 'automatic'),
    abilities: [
      {
        id: 'attacks',
        name: '基础攻击与伤害',
        support: 'automatic',
        cost: 'action',
        detail: '复用原攻击、分类型伤害和预算结算',
      },
      ...(extra.abilities ?? []).map((a) => ({
        id: a.id,
        name: a.name,
        support: a.support,
        cost: a.cost,
        detail: a.note || '独立怪物能力；原预算、次数和结算',
      })),
    ],
    ...meta,
  }
  return {
    id,
    name,
    source,
    metadata,
    notes: [
      '怪物数据块：不授予玩家职业等级或额外法术位',
      '自动／GM边界见能力清单；模板更新不覆盖已有实例',
    ],
    strategy: extra.spellcasting ? 'ranged' : 'nearest',
    body: {
      ...customNpc(),
      name,
      source,
      ac,
      maxHp: hp,
      hp,
      speed,
      scores: values,
      saves,
      initiativeBonus: saves.dex,
      attacks,
      creatureType: 'humanoid',
      size: 'medium',
      ...extra,
      templateMetadata: clone(metadata),
    },
  }
}
