const eq = (
  label: string,
  gp: number,
  list: string,
  choices?: EquipmentOption['choices'],
): EquipmentOption => ({
  label,
  gp,
  items: list
    ? list.split(',').map((x) => {
        const [itemId, n] = x.split(':')
        return { itemId: itemId!, quantity: Number(n || 1) }
      })
    : [],
  choices,
})
